#include <stdio.h>

int main(void) {
    int n = 0;
    
    // Проверка на корректный ввод N
    while (n <= 0) 
    {
        printf("Введите N (сколько чисел вы будете вводить): ");
        if (scanf("%d", &n) != 1 && n <= 0) {
            return 1; 
        }
    }

    int sum = 0;       // Переменная-аккумулятор для суммы
    int count = 0;     // Счетчик введенных чисел
    int current_num;   // Переменная для текущего вводимого числа

    printf("Введите %d чисел:\n", n);
    
    // Цикл while для считывания N чисел
    while (count < n) 
    {
        printf("Число %d: ", count + 1);
        
        if (scanf("%d", &current_num) == 1) 
        {
            // Проверяем, является ли число нечетным
            // Если остаток от деления на 2 не равен 0, значит число нечетное
            if (current_num % 2 != 0) 
            {
                sum += current_num; // Если нечетное — добавляем в сумму
            }
            count++; // Увеличиваем счетчик только если ввод был успешным
        } 
        else 
        {
            return 1;
        }
    }

    // Вывод результата
    printf("Сумма нечетных чисел из введенных: %d\n", sum);

    // Почему используется += (а не =):
    // Оператор = просто присваивает переменной новое значение, полностью стирая старое. 
    // Если бы мы написали sum = counter, то на каждой итерации цикла в переменной sum оставалось бы 
    // только последнее нечетное число, а все предыдущие терялись бы.
    // Оператор += (сложение с присваиванием) берет текущее значение переменной sum, 
    // прибавляет к нему counter и записывает результат обратно в sum. Это позволяет накапливать (аккумулировать) 
    // общую сумму шаг за шагом. То же самое касается оператора *=, который используется для накопления 
    // произведения (факториала): он умножает текущее значение на новое и сохраняет результат.
    // Как работает логика нечетных чисел:
    // Мы начинаем с counter = 1 (первое нечетное число). В конце каждого шага мы прибавляем к счетчику двойку 
    // (counter += 2), чтобы получать следующее нечетное число: 1, 3, 5, 7 и т.д. 
    // Цикл работает до тех пор, пока мы не сложим ровно N чисел (переменная count).

}