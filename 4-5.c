#include <stdio.h>

 /* Функция конвертации байт в килобайты.
 * Принимает double, возвращает double, как требуется в задании.*/
double byte_to_kb(double bytes) {
    /* Коэффициент конвертации. 
     * const защищает переменную от случайного изменения внутри функции. */
    const double BYTES_IN_KB = 1024.0; 
    
    return bytes / BYTES_IN_KB;
}

int main(void) 
{
    double value; /* Введенное значение в байтах */

    printf("Конвертер байт в КБ.\n");
    printf("Введите количество байт (для выхода введите 'q' или нажмите Ctrl+D):\n");

    /* 
     * Условие цикла: scanf пытается считать число с плавающей точкой (%lf).
     * Если ввод успешен, возвращается 1, и цикл продолжается.
     * Если введена буква или достигнут конец файла (EOF), возвращается 0 или -1,
     * условие становится ложным, и цикл корректно завершается.
     */
    while (scanf("%lf", &value) == 1) 
    {
        /* Вызываем функцию и сохраняем результат */
        double result = byte_to_kb(value);
        
        /* Вывод результата с точностью до 2 знаков после запятой */
        printf("%.2f байт = %.2f КБ\n", value, result);
        
        printf("Введите следующее значение (или 'q' для выхода):\n");
    }

}