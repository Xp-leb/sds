#include <stdio.h>

/* Прототип: функция принимает два указателя на double */
void set_average(double *pa, double *pb);

int main(void) {
    double x = 4.0;
    double y = 10.0;

    printf("До вызова функции:\n");
    printf("x = %.2f, y = %.2f\n", x, y);

    /* Передаём адреса переменных с помощью & */
    set_average(&x, &y);

    printf("После вызова функции:\n");
    printf("x = %.2f, y = %.2f\n", x, y);

    return 0;
}

void set_average(double *pa, double *pb)
{
    double sum;
    double avg;

    /* Разыменовываем указатели, чтобы получить значения */
    sum = *pa + *pb;
    avg = sum / 2.0;

    /* Присваиваем обеим переменным среднее арифметическое */
    *pa = avg;
    *pb = avg;
}

/*
 * Передача по значению:
 * В функцию передаётся КОПИЯ значения аргумента. Функция работает
 * с копией и не может изменить оригинальную переменную в main().
 * Пример: void f(double a) { a = 100; } — переменная в main()
 * останется прежней.
 *
 * Передача по указателю:
 * В функцию передаётся АДРЕС переменной (с помощью &). Внутри
 * функции мы разыменовываем указатель (*) и работаем с оригиналом.
 * Поэтому изменения видны в main().
 * Пример: void f(double *pa) { *pa = 100; } — переменная в main()
 * изменится на 100.
 *
 * В нашей программе set_average(&x, &y) передаёт адреса x и y.
 * Внутри функции *pa и *pb — это те же самые x и y из main().
 * Поэтому после вызова обе переменные становятся равны среднему.
 */