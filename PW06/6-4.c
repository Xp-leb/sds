#include <stdio.h>

int main(void) {
    double zapros;      /* количество запросов */
    double cost = 0.0;    /* итоговая стоимость */
    double part1 = 0.0;   /* стоимость первой ступени */
    double part2 = 0.0;   /* стоимость второй ступени */
    double part3 = 0.0;   /* стоимость третьей ступени */

    printf("Введите количество API-запросов: ");

    /* Защита: проверяем, что ввод — действительно число */
    if (scanf("%lf", &zapros) != 1)
    {
        printf("Ошибка: введено не число.\n");
        return 1;
    }

    if (zapros < 0)
    {
        printf("Количество запросов не может быть отрицательным.\n");
        return 1;
    }

    /* Цепочка if...else if...else — как требует задание */
    if (zapros <= 2000)
    {
        /* Вся величина попадает в первую ступень */
        part1 = zapros * 0.02;
        part2 = 0.0;
        part3 = 0.0;

        printf("Ступень 1: %.2f запросов * 0.02 = %.2f\n",
               zapros, part1);
    }
    else if (zapros <= 12000)
    {
        /* Первые 2000 — по 0.02, остальное — по 0.015 */
        part1 = 2000 * 0.02;
        part2 = (zapros - 2000) * 0.015;
        part3 = 0.0;

        printf("Ступень 1: 2000 * 0.02 = %.2f\n", part1);
        printf("Ступень 2: %.2f * 0.015 = %.2f\n",
               zapros - 2000, part2);
    }
    else
    {
        /* Первые 2000 — по 0.02,
           следующие 10000 (с 2000 до 12000) — по 0.015,
           остальное — по 0.01 */
        part1 = 2000 * 0.02;
        part2 = 10000 * 0.015;
        part3 = (zapros - 12000) * 0.01;

        printf("Ступень 1: 2000 * 0.02 = %.2f\n", part1);
        printf("Ступень 2: 10000 * 0.015 = %.2f\n", part2);
        printf("Ступень 3: %.2f * 0.01 = %.2f\n",
               zapros - 12000, part3);
    }

    cost = part1 + part2 + part3;

    printf("Исходная величина: %.2f запросов\n", zapros);
    printf("Итоговая стоимость: %.2f\n", cost);

}