#include <stdio.h>

int main(void) {
    double requests;      /* количество запросов */
    double cost = 0.0;    /* итоговая стоимость */
    double part1 = 0.0;   /* стоимость первой ступени */
    double part2 = 0.0;   /* стоимость второй ступени */
    double part3 = 0.0;   /* стоимость третьей ступени */

    printf("Введите количество API-запросов: ");
    scanf("%lf", &requests);

    if (requests < 0)
    {
        printf("Количество запросов не может быть отрицательным.\n");
        return 1;
    }

    /* Цепочка if...else if...else — как требует задание */
    if (requests <= 2000)
    {
        /* Вся величина попадает в первую ступень */
        part1 = requests * 0.02;
        part2 = 0.0;
        part3 = 0.0;

        printf("Ступень 1 (до 2000): %.2f запросов * 0.02 = %.2f\n",
               requests, part1);
    }
    else if (requests <= 12000)
    {
        /* Первые 2000 — по 0.02, остальное — по 0.015 */
        part1 = 2000 * 0.02;
        part2 = (requests - 2000) * 0.015;
        part3 = 0.0;

        printf("Ступень 1 (до 2000): 2000 * 0.02 = %.2f\n", part1);
        printf("Ступень 2 (2000-12000): %.2f * 0.015 = %.2f\n",
               requests - 2000, part2);
    }
    else
    {
        /* Первые 2000 — по 0.02,
           следующие 10000 (с 2000 до 12000) — по 0.015,
           остальное — по 0.01 */
        part1 = 2000 * 0.02;
        part2 = 10000 * 0.015;
        part3 = (requests - 12000) * 0.01;

        printf("Ступень 1 (до 2000): 2000 * 0.02 = %.2f\n", part1);
        printf("Ступень 2 (2000-12000): 10000 * 0.015 = %.2f\n", part2);
        printf("Ступень 3 (свыше 12000): %.2f * 0.01 = %.2f\n",
               requests - 12000, part3);
    }

    cost = part1 + part2 + part3;

    printf("Исходная величина: %.2f запросов\n", requests);
    printf("Итоговая стоимость: %.2f\n", cost);

}

/*
 * Почему для денежных расчётов лучше double, а не float:
 *
 * Тип float хранит около 7 значащих цифр (лекция 2, стр. 26).
 * Тип double хранит около 15 значащих цифр (лекция 2, стр. 26).
 *
 * В денежных расчётах важна точность до копеек, а при
 * многократном умножении и сложении дробных чисел ошибка
 * округления во float может накопиться и привести к
 * неверному результату (например, 0.02 + 0.02 во float
 * может дать не ровно 0.04, а 0.039999...).
 *
 * double даёт гораздо меньшую ошибку округления, поэтому
 * для финансовых вычислений предпочтительнее double.
 *
 * Кроме того, в scanf и printf для double используется
 * формат %lf (при вводе) и %f (при выводе), а для float —
 * %f (при вводе). Если перепутать, программа может
 * работать неправильно.
 */