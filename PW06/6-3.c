#include <stdio.h>

int main(void) {
    int num;
    int kratno3 = 0;
    int kratno5 = 0;
    int sum3 = 0;
    int sum5 = 0;
    double avg3;
    double avg5;

    printf("Введите целые числа (0 для завершения):\n");

    /* Читаем первое число */
    scanf("%d", &num);

    while (num != 0)
    {
        /* Проверяем, кратно ли число 3 */
        if (num % 3 == 0)
        {
            kratno3 = kratno3 + 1;
            sum3 = sum3 + num;
        }

        /* Проверяем, кратно ли число 5 */
        if (num % 5 == 0)
        {
            kratno5 = kratno5 + 1;
            sum5 = sum5 + num;
        }

        /* Читаем следующее число */
        scanf("%d", &num);
    }

    /* Выводим результаты для кратных 3 */
    printf("Чисел, кратных 3: %d\n", kratno3);
    if (kratno3 > 0)
    {
        /* Явное приведение к double, чтобы деление было вещественным */
        avg3 = (double)sum3 / kratno3;
        printf("Среднее арифметическое для кратных 3: %.2f\n", avg3);
    }
    else
    {
        printf("Среднее арифметическое для кратных 3: нет чисел\n");
    }

    /* Выводим результаты для кратных 5 */
    printf("Чисел, кратных 5: %d\n", kratno5);
    if (kratno5 > 0)
    {
        avg5 = (double)sum5 / kratno5;
        printf("Среднее арифметическое для кратных 5: %.2f\n", avg5);
    }
    else
    {
        printf("Среднее арифметическое для кратных 5: нет чисел\n");
    }

}


/*
 * Ленивое вычисление (short-circuit evaluation):
 *
 * В выражении A && B сначала вычисляется A.
 * Если A ложно (0), то B уже НЕ вычисляется,
 * потому что результат всего выражения уже точно ложен.
 *
 * В выражении A || B сначала вычисляется A.
 * Если A истинно (не 0), то B уже НЕ вычисляется,
 * потому что результат всего выражения уже точно истинен.
 *
 * Это важно, например, в такой проверке:
 *   if (count3 > 0 && sum3 / count3 > 10)
 * Здесь деление sum3 / count3 выполнится только если count3 > 0.
 * Если бы count3 был равен 0, деления бы не произошло,
 * и программа не упала бы с ошибкой деления на ноль.
 *
 * В нашей программе мы используем if (count3 > 0) отдельно,
 * чтобы явно показать эту идею, но тот же эффект дал бы
 * оператор && в составном условии.
 */