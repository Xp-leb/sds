#include <stdio.h>

int main(void) {
    double A = 1.0, B = 4.0, H = 0.5;
    double x, y;
    int n = 0;

    printf("N\tX\tY\n");

    for (x = A; x <= B; x = x + H)
    {
        y = x * x * x;
        n++;
        printf("%d\t%.4f\t%.4f\n", n, x, y);
    }

}


// В цикле for счётчик x — вещественный, и на каждом шаге мы прибавляем H. 
// Проблема в том, что не все дробные числа в компьютере хранятся точно. 
// Например, 0.1 в двоичной системе — бесконечная дробь, поэтому при x = x + H накапливается маленькая ошибка. 
// Из-за этого x в конце может стать чуть больше или чуть меньше 4.0, и условие x <= B 
// сработает неправильно: либо последняя точка пропадёт, либо появится лишняя. 
// В моём варианте H = 0.5, а 0.5 — это степень двойки, она хранится точно, 
// поэтому тут всё нормально. Но если бы H было 0.1, то ошибка была бы заметна.